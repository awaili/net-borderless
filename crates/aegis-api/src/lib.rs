//! # aegis-api
//!
//! 本地 API（架构 L3）——核心引擎对外唯一契约。
//!
//! - REST：Profile/订阅/节点/规则 CRUD，探活触发，诊断触发
//! - WS：连接表、状态、诊断进度实时推送
//! - 鉴权：绑定 127.0.0.1 / Unix socket（多用户 0600）+ 每次启动随机 token
//! - OpenAPI schema 导出（第三方工具可基于此接入）
//!
//! 分层硬规则：任何 crate 不得依赖本 crate（它是依赖图的终点，CI 强制）。
//! UI（apps/*）、CLI、测试脚本全部走同一 API，核心逻辑只有一份实现。
